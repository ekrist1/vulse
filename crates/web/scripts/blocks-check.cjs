const { chromium } = require("playwright-core");
const assert = require("node:assert/strict");
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || "/usr/bin/chromium", headless: true, args: ["--no-sandbox", "--disable-dev-shm-usage"] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const base = process.env.VULSE_TEST_URL || "http://127.0.0.1:8098";
  const errors = [];
  page.on("pageerror", (e) => errors.push(e.message));
  try {
    await page.goto(base + "/register");
    const handle = "blocks" + Date.now();
    await page.getByLabel("Email").fill(handle + "@example.com");
    await page.getByLabel("Handle").fill(handle);
    await page.getByLabel("Password").fill("test-password");
    await page.getByRole("button", { name: "Create account", exact: true }).click();
    await page.getByRole("heading", { name: "A home for your data." }).waitFor();
    const response = await page.request.post(base + "/api/v1/collections", { data: { name: "articles", visibility: "public", blueprint: { fields: [{ name: "content", type: "portable_text" }] } } });
    assert.equal(response.status(), 201);
    const { id } = await response.json();
    await page.goto(base + `/collections/${id}/documents/new`);
    const editor = page.getByRole("textbox", { name: "content", exact: true });
    await editor.waitFor();
    await editor.fill("Introduction");
    await page.keyboard.press("End");
    await page.keyboard.press("Enter");
    async function insert(name) {
      await page.getByRole("button", { name: "+ Insert block", exact: true }).click();
      await page.locator(".rich-insert-choice").filter({ has: page.getByText(name, { exact: true }) }).click();
    }
    await insert("Accordion");
    const accordion = page.locator(".tiptap > .rich-accordion");
    await accordion.getByLabel("Accordion heading").fill("Frequently asked questions");
    await accordion.locator(":scope > .rich-block-content > p").click();
    await page.keyboard.type("The answer is editable rich text.");
    await page.getByRole("button", { name: "Bold", exact: true }).click();
    await page.keyboard.type(" Bold answer");
    await page.getByRole("button", { name: "Bold", exact: true }).click();
    assert.equal(await accordion.locator("strong").innerText(), " Bold answer");
    await accordion.getByRole("button", { name: "Collapse", exact: true }).click();
    assert.equal(await accordion.locator(":scope > .rich-block-content").isVisible(), false);
    await accordion.getByRole("button", { name: "Expand", exact: true }).click();
    await accordion.getByLabel("Start collapsed").check();
    await accordion.getByRole("button", { name: "Expand", exact: true }).click();
    await page.locator(".tiptap > p").last().click();
    await insert("Repeatable text");
    const group = page.locator(".tiptap > .rich-repeatable");
    await group.getByLabel("Repeatable group title").fill("Highlights");
    const entries = group.locator(":scope > .rich-block-content > .rich-repeatableItem");
    await entries.first().getByLabel("Entry label").fill("First");
    await entries.first().locator(":scope > .rich-block-content > p").click();
    await page.keyboard.type("First entry body");
    await group.getByRole("button", { name: "Add entry", exact: true }).click();
    await entries.nth(1).getByLabel("Entry label").fill("Second");
    await entries.nth(1).locator(":scope > .rich-block-content > p").click();
    await page.keyboard.type("Second entry body");
    await entries.nth(1).getByRole("button", { name: "Move up", exact: true }).click();
    assert.equal(await entries.first().getByLabel("Entry label").inputValue(), "Second");
    await page.getByRole("button", { name: "Undo", exact: true }).click();
    assert.equal(await entries.first().getByLabel("Entry label").inputValue(), "First");
    await page.getByRole("button", { name: "Redo", exact: true }).click();
    assert.equal(await entries.first().getByLabel("Entry label").inputValue(), "Second");
    await group.getByRole("button", { name: "Add entry", exact: true }).click();
    await entries.nth(2).getByRole("button", { name: "Remove entry", exact: true }).click();
    assert.equal(await entries.count(), 2);
    await entries.first().locator(":scope > .rich-block-content > p").click();
    await page.keyboard.press("End");
    await page.keyboard.press("Enter");
    await insert("Accordion");
    const nested = group.locator(".rich-accordion");
    await nested.getByLabel("Accordion heading").fill("Nested details");
    await nested.locator(":scope > .rich-block-content > p").click();
    await page.keyboard.type("Nested answer");
    await page.locator(".rich-editor input[type=file]").setInputFiles({ name: "pixel.png", mimeType: "image/png", buffer: Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/xSsAAAAASUVORK5CYII=", "base64") });
    await page.getByText("Image added.", { exact: true }).waitFor();
    assert.equal(await nested.locator("img").count(), 1);
    await page.locator(".tiptap > p").last().click();
    await insert("Iframe embed");
    const dialog = page.getByRole("dialog");
    await dialog.getByLabel("Embed URL").fill("https://user:password@embed.example.test/content");
    await dialog.getByRole("button", { name: "Add embed", exact: true }).click();
    await dialog.getByRole("alert").filter({ hasText: "credentials" }).waitFor();
    await dialog.getByLabel("Embed URL").fill("https://youtu.be/dQw4w9WgXcQ");
    await dialog.getByLabel("Embed title").fill("Demo video");
    await dialog.getByLabel("Height (pixels)").fill("400");
    await dialog.getByRole("button", { name: "Add embed", exact: true }).click();
    const embed = page.locator(".rich-embed");
    assert((await embed.innerText()).includes("youtube-nocookie.com/embed/"));
    await embed.getByRole("button", { name: "Edit embed", exact: true }).click();
    await dialog.getByLabel("Embed URL").fill("https://embed.example.test/content");
    await dialog.getByRole("button", { name: "Update embed", exact: true }).click();
    await page.route("https://embed.example.test/**", (route) => route.fulfill({ contentType: "text/html", body: "<p>Embedded preview</p>" }));
    await embed.getByRole("button", { name: "Load preview", exact: true }).click();
    assert.equal(await embed.locator("iframe").getAttribute("title"), "Demo video");
    assert(!(await embed.locator("iframe").getAttribute("sandbox")).includes("allow-same-origin"));
    await page.frameLocator(".rich-embed iframe").getByText("Embedded preview").waitFor();
    await page.screenshot({ path: "/tmp/vulse-editor-blocks.png", fullPage: true });
    await page.getByRole("button", { name: "Save record", exact: true }).click();
    await page.waitForURL(/documents\/(?!new)[^/]+$/);
    const recordId = page.url().split("/").pop();
    const endpoint = base + `/api/v1/collections/${id}/documents/${recordId}`;
    const saved = await (await page.request.get(endpoint)).json();
    const content = saved.body.content;
    assert(content.some((block) => block._type === "accordion" && block.collapsed && block.content.some((text) => text.children?.some((span) => span.marks.includes("strong")))));
    const repeat = content.find((block) => block._type === "repeatable");
    assert.deepEqual(repeat.items.map((item) => item.label), ["Second", "First"]);
    assert(repeat.items[0].content.find((block) => block._type === "accordion").content.some((block) => block._type === "image"));
    assert(content.some((block) => block._type === "iframe" && block.height === 400));
    const publicDoc = await (await page.request.get(base + `/api/v1/public/${handle}/articles/${recordId}`)).json();
    assert.deepEqual(publicDoc.body.content, content);
    await page.reload();
    await editor.waitFor();
    assert.equal(await accordion.locator(":scope > .rich-block-content").isVisible(), false);
    await accordion.getByRole("button", { name: "Expand", exact: true }).click();
    assert((await accordion.innerText()).includes("The answer is editable rich text."));
    assert.equal(await group.locator("img").count(), 1);
    await page.getByRole("button", { name: "Save record", exact: true }).click();
    await page.getByText("Record saved", { exact: true }).waitFor();
    assert.deepEqual((await (await page.request.get(endpoint)).json()).body.content, content);
    await page.setViewportSize({ width: 390, height: 844 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    await page.screenshot({ path: "/tmp/vulse-editor-blocks-mobile.png", fullPage: true });
    await embed.getByRole("button", { name: "Edit embed", exact: true }).click();
    await dialog.getByLabel("Height (pixels)").fill("450");
    await dialog.getByRole("button", { name: "Update embed", exact: true }).click();
    await embed.getByRole("button", { name: "Remove block", exact: true }).click();
    assert.equal(await embed.count(), 0);
    await page.getByRole("button", { name: "Undo", exact: true }).click();
    assert.equal(await embed.count(), 1);
    assert.deepEqual(errors, []);
    console.log("PASS: block insertion; accordion heading/formatting/collapse; repeatable labels, add/remove/reorder/history; nested blocks and image upload; iframe URL validation, share links, edit and sandboxed preview; save/reload and public API preservation; mobile layout; no runtime errors");
  } catch (error) {
    await page.screenshot({ path: "/tmp/vulse-editor-blocks-failure.png", fullPage: true });
    console.error("Browser errors:", errors);
    throw error;
  } finally { await browser.close(); }
})();
