const { chromium } = require("playwright-core");
const assert = require("node:assert/strict");
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || "/usr/bin/chromium", headless: true, args: ["--no-sandbox", "--disable-dev-shm-usage"] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1e3 } });
  const base = process.env.VULSE_TEST_URL || "http://127.0.0.1:8098";
  const errors = [];
  page.on("pageerror", (e) => errors.push(e.message));
  try {
    await page.goto(base + "/register");
    await page.getByLabel("Email").fill("editor" + Date.now() + "@example.com");
    await page.getByLabel("Handle").fill("editor" + Date.now());
    await page.getByLabel("Password").fill("test-password");
    await page.getByRole("button", { name: "Create account", exact: true }).click();
    await page.getByRole("heading", { name: "A home for your data." }).waitFor();
    const created = await page.request.post(base + "/api/v1/collections", { data: { name: "articles", visibility: "private", blueprint: { fields: [{ name: "title", type: "string" }, { name: "content", type: "portable_text" }, { name: "price", type: "number" }, { name: "total", type: "calculated", formula: "=[price]*2" }] } } });
    assert.equal(created.status(), 201);
    const collection = await created.json();
    const id = collection.id;
    const original = [{ _key: "heading", _type: "block", style: "h1", markDefs: [], children: [{ _key: "heading_span", _type: "span", text: "Existing heading \u{1F600}", marks: ["strong"] }] }, { _key: "paragraph", _type: "block", style: "normal", markDefs: [], children: [{ _key: "s1", _type: "span", text: "Preserved ", marks: [] }, { _key: "s2", _type: "span", text: "formatting", marks: ["em", "strong"] }] }, { _key: "listed", _type: "block", style: "blockquote", listItem: "bullet", level: 1, markDefs: [], children: [{ _key: "listed_span", _type: "span", text: "Existing list quote", marks: [] }] }];
    const made = await page.request.post(base + `/api/v1/collections/${id}/documents`, { data: { body: { title: "Old content", content: original, price: 10 } } });
    assert.equal(made.status(), 201);
    const record = await made.json();
    await page.goto(base + `/collections/${id}/documents/${record.id}`);
    await page.getByRole("textbox", { name: "content", exact: true }).waitFor();
    assert.equal(await page.locator(".tiptap h1").innerText(), "Existing heading \u{1F600}");
    await page.getByLabel("title", { exact: true }).fill("Changed title only");
    await page.getByRole("button", { name: "Save record", exact: true }).click();
    await page.getByText("Record saved", { exact: true }).waitFor();
    let read = await (await page.request.get(base + `/api/v1/collections/${id}/documents/${record.id}`)).json();
    assert.deepEqual(read.body.content, original);
    await page.goto(base + `/collections/${id}/documents/new`);
    const editor = page.getByRole("textbox", { name: "content", exact: true });
    await editor.waitFor();
    await page.getByLabel("title", { exact: true }).fill("New content");
    await page.getByLabel("price", { exact: true }).fill("21");
    await editor.fill("Hello");
    await page.keyboard.press("End");
    await page.keyboard.type(" world \u{1F600}");
    assert.equal(await editor.innerText(), "Hello world \u{1F600}");
    await page.getByRole("button", { name: "Undo", exact: true }).click();
    assert.notEqual(await editor.innerText(), "Hello world \u{1F600}");
    await page.getByRole("button", { name: "Redo", exact: true }).click();
    assert.equal(await editor.innerText(), "Hello world \u{1F600}");
    await editor.click();
    await page.keyboard.press("Control+a");
    await page.getByRole("button", { name: "Bold", exact: true }).click();
    assert.equal(await page.locator(".tiptap strong").innerText(), "Hello world \u{1F600}");
    await page.getByRole("button", { name: "Underline", exact: true }).click();
    assert.equal(await page.locator(".tiptap u").innerText(), "Hello world \u{1F600}");
    await page.getByLabel("Paragraph style").selectOption("2");
    assert.equal(await page.locator(".tiptap h2").innerText(), "Hello world \u{1F600}");
    await editor.focus();
    await page.keyboard.press("ArrowRight");
    await page.keyboard.press("Control+End");
    await page.keyboard.press("Enter");
    await page.keyboard.type("First item");
    await page.getByRole("button", { name: "Bullet list", exact: true }).click();
    await page.keyboard.press("End");
    await page.keyboard.press("Enter");
    await page.keyboard.type("Nested item");
    await page.keyboard.press("Tab");
    assert(await page.locator(".tiptap ul ul").count() > 0);
    await page.route("**/assets", async (route) => {
      if (route.request().method() === "POST") await new Promise((r) => setTimeout(r, 700));
      await route.continue();
    });
    await page.locator(".rich-editor input[type=file]").setInputFiles({ name: "pixel.png", mimeType: "image/png", buffer: Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/xSsAAAAASUVORK5CYII=", "base64") });
    await page.keyboard.type(" typed during upload");
    await page.getByText("Image added.", { exact: true }).waitFor();
    assert((await editor.innerText()).includes("typed during upload"));
    assert.equal(await page.locator(".tiptap img").count(), 1);
    await page.screenshot({ path: "/tmp/vulse-tiptap-editor.png", fullPage: true });
    await page.getByRole("button", { name: "Save record", exact: true }).click();
    await page.waitForURL(/documents\/(?!new)[^/]+$/);
    const recordId = page.url().split("/").pop();
    read = await (await page.request.get(base + `/api/v1/collections/${id}/documents/${recordId}`)).json();
    assert.equal(read.body.total, 42);
    assert(read.body.content.some((b) => b._type === "image" && b.asset._ref));
    assert(read.body.content.some((b) => b.level === 2));
    assert(read.body.content.some((b) => b.style === "h2" && b.children.some((s) => s.marks.includes("strong") && s.marks.includes("underline"))));
    await page.reload();
    await editor.waitFor();
    assert((await editor.innerText()).includes("typed during upload"));
    assert.equal(await page.locator(".tiptap img").count(), 1);
    await page.getByRole("button", { name: "Save record", exact: true }).click();
    await page.getByText("Record saved", { exact: true }).waitFor();
    const reloaded = await (await page.request.get(base + `/api/v1/collections/${id}/documents/${recordId}`)).json();
    assert.deepEqual(reloaded.body.content, read.body.content);
    await page.getByRole("link", { name: "Back to records" }).click();
    await page.getByRole("button", { name: "API", exact: true }).click();
    await page.getByRole("heading", { name: "Build with your collection" }).waitFor();
    assert((await page.locator(".api-panel").innerText()).includes(id));
    assert((await page.locator(".api-panel").innerText()).includes("This collection is private."));
    const createCode = await page.locator(".api-code").filter({ hasText: "Create request" }).locator("code").innerText();
    assert(createCode.includes('"content"'));
    assert(!createCode.includes('"total"'));
    await page.getByRole("button", { name: "Copy List request", exact: true }).click();
    await page.getByText("Copied", { exact: true }).waitFor();
    await page.screenshot({ path: "/tmp/vulse-collection-api.png", fullPage: true });
    await page.getByRole("button", { name: "Settings", exact: true }).click();
    await page.getByLabel("Who can read your data?").selectOption("public");
    await page.getByRole("button", { name: "Save changes", exact: true }).click();
    await page.getByText("Changes saved", { exact: true }).waitFor();
    await page.getByRole("button", { name: "API", exact: true }).click();
    await page.getByText(/This collection is public/).waitFor();
    const publicCode = await page.locator(".api-code").filter({ hasText: "Public list request" }).locator("code").innerText();
    assert(!publicCode.includes("Authorization"));
    const publicUrl = publicCode.match(/curl '([^']+)'/)[1];
    const publicResult = await page.request.get(publicUrl);
    assert.equal(publicResult.status(), 200);
    assert.equal((await publicResult.json()).items.length, 2);
    await page.setViewportSize({ width: 390, height: 844 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    await page.screenshot({ path: "/tmp/vulse-collection-api-mobile.png", fullPage: true });
    assert.deepEqual(errors, []);
    console.log("PASS: existing Portable Text preservation; Tiptap typing, selection, marks, headings, nested lists, undo/redo, upload during editing, save/reload; API tab, schema-based examples, clipboard, public/private reads, mobile layout; no runtime errors");
  } catch (error) {
    await page.screenshot({ path: "/tmp/vulse-editor-api-failure.png", fullPage: true });
    console.error("Browser errors:", errors);
    throw error;
  } finally {
    await browser.close();
  }
})();
